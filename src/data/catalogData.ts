// Helper to construct normalized 20-length theme vector
export function buildThemeVector(themes: string[]): number[] {
  const raw: number[] = FIXED_20_THEMES.map((t) => (themes.includes(t) ? 1.0 : 0.0));
  const magnitude = Math.sqrt(raw.reduce((sum: number, val: number): number => sum + val * val, 0));
  if (magnitude === 0) return raw;
  return raw.map((val) => Number((val / magnitude).toFixed(4)));
}

